#!/usr/bin/env python3
"""Build the offline-safe browser data bundle from the single editorial source."""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
source = ROOT / 'content.json'
data = json.loads(source.read_text(encoding='utf-8'))
assert isinstance(data.get('posts'), list) and data['posts'], 'posts must be a nonempty list'
seen = set()
for post in data['posts']:
    assert post['id'] not in seen, f"Duplicate post id: {post['id']}"
    seen.add(post['id'])
    assert post['category'] in {'industry', 'product', 'practice', 'embedded'}
    assert post['region'] in {'china', 'global'}
    assert post.get('title') and post.get('dek') and post.get('sources')
    for source in post['sources']:
        assert source['url'].startswith('https://'), f"Expected HTTPS source: {source['url']}"
# Escaping < protects against a future inline embedding; this is served as a separate script.
payload = json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')
(ROOT / 'content-data.js').write_text(
    '// Generated from content.json by build.py. Do not edit this file directly.\n'
    'window.AI_FIELDNOTES = ' + payload + ';\n', encoding='utf-8')
# One deterministic cache key covers the complete CSS/JS/data release. Hash the
# final generated bundle, not the HTML markers, so rebuilding is idempotent.
ASSET_FILES = (
    'style.css', 'visuals.css', 'content-data.js', 'site-core.js',
    'visuals.js', 'app.js', 'favicon.svg',
)
digest = hashlib.sha256()
for filename in ASSET_FILES:
    asset = (ROOT / filename).read_bytes()
    digest.update(filename.encode('utf-8') + b'\0')
    digest.update(str(len(asset)).encode('ascii') + b'\0' + asset + b'\0')
release = '20261017r1-' + digest.hexdigest()[:12]
index_path = ROOT / 'index.html'
markup = index_path.read_text(encoding='utf-8')
for filename in ASSET_FILES:
    pattern = r'((?:src|href)="\./' + re.escape(filename) + r')(?:\?[^"#]*)?"'
    markup, count = re.subn(pattern, lambda m: m.group(1) + '?v=' + release + '"', markup)
    assert count >= 1, f'Missing asset URL in index.html: {filename}'
markup, marker_count = re.subn(r'(data-release=")[^"]*(")', lambda m: m.group(1) + release + m.group(2), markup)
assert marker_count >= 2, 'Expected HTML and footer release markers'
markup, meta_count = re.subn(r'(<meta name="app-release" content=")[^"]*(")', lambda m: m.group(1) + release + m.group(2), markup)
assert meta_count == 1, 'Expected one app-release metadata marker'
markup, footer_count = re.subn(r'(<small\b[^>]*id="release-version"[^>]*>)[^<]*(</small>)', lambda m: m.group(1) + '版本 ' + release + m.group(2), markup)
assert footer_count == 1, 'Expected one visible footer release marker'
index_path.write_text(markup, encoding='utf-8')
print(f'Built content-data.js: {len(data["posts"])} articles, verified {data["site"]["verifiedAt"]}.')
print(f'Asset release: {release}')
